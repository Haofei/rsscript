fn coverage_bucket_from_supported(supported: &[&str]) -> CoverageBucket {
    let mut supported = supported
        .iter()
        .map(|item| (*item).to_string())
        .collect::<Vec<_>>();
    supported.sort();
    supported.dedup();
    let all = supported.clone();
    CoverageBucket {
        all,
        supported,
        missing: Vec::new(),
    }
}
